-- ============================================================================
-- 07_add_sales_manager_role.sql
-- מודול CRM · לפני גל 0ג · הוספת תפקיד "מנהל מכירות" ל-enum user_role
--
-- רקע: app_users.role אינו טקסט חופשי אלא enum בשם user_role, עם שישה ערכים:
--   admin | sales | studio_manager | editor | office_manager | editing_manager
-- לכן אי אפשר להוסיף תפקיד בקוד בלבד — ה-DB ידחה כל ערך שאינו ב-enum.
--
-- ⚠️ שתי אזהרות שחשוב לקרוא לפני ההרצה:
--
-- 1. אין כאן BEGIN/COMMIT במכוון. ב-PostgreSQL לא ניתן להשתמש בערך enum חדש
--    באותה טרנזקציה שבה הוא נוסף. להריץ את הקובץ הזה לבדו, ואת בדיקות
--    האימות בהרצה נפרדת אחריו.
--
-- 2. ⚠️ זהו הצעד הראשון בכל התוכנית שאינו הפיך. אי אפשר להסיר ערך מ-enum
--    ב-PostgreSQL. ביטול אמיתי היה דורש יצירת טיפוס חדש והמרה של כל עמודה
--    שמשתמשת בו.
--    בפועל המחיר אפסי: ערך enum שאינו בשימוש אינו מזיק ואינו משפיע על דבר.
--    אבל שווה שתדע שזו דלת חד-כיוונית, בניגוד לטבלאות שאפשר פשוט למחוק.
-- ============================================================================

alter type user_role add value if not exists 'sales_manager' after 'sales';
